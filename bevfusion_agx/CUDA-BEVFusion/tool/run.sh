# Keep the two libspconv implementations in separate build directories.
if [ "${BEVFUSION_SPARSE_BACKEND:-nvidia}" = "open" ]; then
    export BuildDirectory=${BuildDirectory:-$(pwd)/build/open}
else
    export BuildDirectory=${BuildDirectory:-$(pwd)/build}
fi

# configure the environment
. tool/environment.sh

if [ "$ConfigurationStatus" != "Success" ]; then
    echo "Exit due to configure failure."
    exit 1
fi

set -e

# Protobuf sources are generated by CMake with the installed protoc.
bevfusion_source_dir=$(pwd)
mkdir -p "$BuildDirectory"
(
    cd "$BuildDirectory"
    cmake "$bevfusion_source_dir" \
        -DBEVFUSION_SPARSE_BACKEND="$BEVFUSION_SPARSE_BACKEND" \
        -DBEVFUSION_CUDA_ARCH="$CUDASM" \
        -DSPCONV_CUDA_VERSION="$SPCONV_CUDA_VERSION" \
        -DCMAKE_BUILD_PYTHON="$USE_Python"
)
cmake --build "$BuildDirectory" -- -j"${BUILD_JOBS:-2}"

"$BuildDirectory/bevfusion" "$DEBUG_DATA" "$DEBUG_MODEL" "$DEBUG_PRECISION"
